import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { format, resolveConfig } from "prettier";

const ROOT = path.resolve(import.meta.dirname, "..");
const CAROLS_DIR = path.join(ROOT, "data/carols");
const OUT = path.join(ROOT, "site/slugs.ts");

const slugs = (await readdir(CAROLS_DIR))
	.filter((file) => file.endsWith(".json"))
	.map((file) => path.basename(file, ".json"))
	.sort();

const source = `// Generated by \`pnpm slugs\` from data/carols/; do not edit.

/** A carol with a transcription at data/carols/<slug>.json. */
export type Slug = ${slugs.map((slug) => JSON.stringify(slug)).join(" | ")};
`;

const options = await resolveConfig(OUT);
await writeFile(OUT, await format(source, { ...options, filepath: OUT }));
